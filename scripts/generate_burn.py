def generate(onnx_path, out_name, post, patch, simplify, tmp, onnx2burn):
    name = os.path.splitext(os.path.basename(onnx_path))[0]
    source = onnx_path
    if patch:
        # Rewrite a copy for code generation; weights are still traced to the original file.
        source = os.path.join(tmp, f"{name}.patched.onnx")
        onnx.save(patch(onnx.load(onnx_path)), source, save_as_external_data=True, location=f"{name}.patched.data")
    flags = ["--no-development"] + ([] if simplify else ["--no-simplify"])
    run = subprocess.run([onnx2burn, *flags, source, os.path.join(tmp, name)],
                         stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True, env={**os.environ, "RUST_LOG": "error"})
    if run.returncode != 0:
        reason = [line for line in run.stderr.splitlines() if "Failed" in line or "panicked" in line]
        raise SystemExit(f"onnx2burn failed on {onnx_path}:\n" + "\n".join(reason[-2:] or run.stderr.splitlines()[-5:]))
    generated = os.path.join(tmp, name, os.path.splitext(os.path.basename(source))[0])
    code = open(f"{generated}.rs").read()
    # Drop onnx2burn's own header: it holds a local path.
    code = trim_model_code(code.split("\n", 1)[1])
    rows = trace(onnx_path, f"{generated}.bpk")
    if post:
        code, rows = post(code, rows)

    header = HEADER.format(src=os.path.basename(onnx_path), ver=BURN_ONNX_VERSION)
    with open(os.path.join(OUT, f"{out_name}.rs"), "w") as f:
        f.write(header + code)
    with open(os.path.join(OUT, f"{out_name}_weights.rs"), "w") as f:
        f.write(header)
        f.write("// Where each burn parameter's data comes from; see src/burn_backend/onnx.rs.\n")
        f.write("use crate::burn_backend::onnx::{Source::*, Transform::*, Weight};\n\n")
        f.write("pub(crate) const WEIGHTS: &[Weight] = &[\n")
        for path, shape, expr in rows:
            shape_expr = "None" if shape is None else f"Some(&{list(shape)})"
            f.write(f'    Weight {{ path: "{path}", shape: {shape_expr}, source: {expr} }},\n')
        f.write("];\n")
    kinds = {}
    for _, _, e in rows:
        k = re.match(r'(Param\("[^"]*", )?(\w+)', e).group(2)
        kinds[k] = kinds.get(k, 0) + 1
    print(f"{out_name}: {len(rows)} tensors {kinds}")


def main():
    parser = argparse.ArgumentParser(description="Generate burn model code for parakeet-rs.")
    parser.add_argument("model", choices=sorted(MODELS))
    parser.add_argument("model_dir", help="Folder with the model's reference ONNX export")
    parser.add_argument("--onnx2burn", default="onnx2burn", help=f"onnx2burn binary (burn-onnx {BURN_ONNX_VERSION})")
    args = parser.parse_args()

    version = subprocess.run([args.onnx2burn, "--version"], capture_output=True, text=True).stdout.strip()
    if BURN_ONNX_VERSION not in version:
        raise SystemExit(f"need onnx2burn {BURN_ONNX_VERSION}, found {version!r}")

    reference, graphs = MODELS[args.model]
    print(f"{args.model}: reference export {reference}")
    os.makedirs(OUT, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        for g in graphs:
            generate(os.path.join(args.model_dir, g["file"]), g["name"], g["post"], g["patch"], g["simplify"], tmp, args.onnx2burn)


if __name__ == "__main__":
    main()
