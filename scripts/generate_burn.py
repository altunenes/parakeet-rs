# Generate the burn backend's model code (src/burn_backend/generated/) from ONNX exports.
# Users never run this: the generated code is checked in. Run it again only when upgrading burn
# or adding a model.
#
# burn runs models written as Rust code, not .onnx files. For each ONNX graph of a model:
#   1. onnx2burn (burn-onnx's converter, same version as the `burn` dependency) writes the graph
#      as Rust model code, plus a .bpk file with the same weights in burn's own format.
#   2. The model code is trimmed to what parakeet-rs uses (no .bpk loading), and sizes that vary
#      between checkpoints of one architecture (e.g. the vocabulary) become parameters.
#   3. Every tensor in the .bpk is traced back to its ONNX source by content, giving a table that
#      parakeet-rs uses to load weights straight from the user's .onnx files, so users download
#      nothing new and no .bpk is ever shipped:
#        - model weights are looked up by a key that does not depend on the export: the
#          initializer's name, or for anonymous initializers ("onnx::MatMul_123") the nodes
#          that consume it;
#        - small graph constants (scalars) are embedded in the table.
#      Anything that cannot be traced is an error. The .bpk is then thrown away.
# No ONNX file is modified.
#
# Requirements:
#   cargo install burn-onnx --version 0.22.0 --locked     (provides onnx2burn)
#   pip install onnx numpy cbor2
#
# Usage:
#   python scripts/generate_burn.py <model> <model dir> [--onnx2burn path/to/onnx2burn]
# where <model> is one of the MODELS below, and <model dir> holds its reference export.
# Then check the result against ONNX Runtime with scripts/check_burn_parity.sh.

